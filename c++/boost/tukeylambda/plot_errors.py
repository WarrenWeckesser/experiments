import sys
import numpy as np
import matplotlib.pyplot as plt


def show_use_and_exit(errcode):
    print(f"use: {sys.argv[0]} filename heading1 heading2 ...")
    print("where filename is the name of the file containing the generated data")
    print("generated by tl_invcdf_measure_errors or tl_invcdf_measure_errors_fixed_lam,")
    print("and the remaining parameters are the column heading from that file.")
    sys.exit(errcode)


if len(sys.argv) < 3:
    show_use_and_exit(0)

fn = sys.argv[1]
selection = sys.argv[2:]
with open(fn, 'r') as f:
    line = f.readline()
# The first line is assumed to be '# param = value', e.g. '# lam = 0.05'
print(f"{line = }")
param_name, param_value_str = [part.strip() for part in line[1:].split('=')]
param_value = float(param_value_str)

data = np.genfromtxt(fn, names=True, skip_header=1)
names = data.dtype.names
for fieldname in selection:
    if fieldname not in names:
        msg = (f"{fieldname} is not an output column heading in {fn}.\n"
               f"Headings are {names[1:]}.")
        raise RuntimeError(msg)

xlabel = names[0]
fig, ax = plt.subplots(len(selection), 1)
for k, name in enumerate(selection):
    ax[k].plot(data[xlabel], data[name], linewidth=1.5, alpha=0.75, label=name)
    ax[k].legend(framealpha=1, shadow=True)
    ax[k].semilogy()
    ax[k].set_ylim(1e-18, 5e-13)
    ax[k].set_xlim(-0.05, 1.05)
    ax[k].grid(True)
    if k == 0:
        ax[k].set_title(f'{param_name} = {param_value}')
plt.xlabel(xlabel)
fig.tight_layout()
plt.show()
